// Copies contract ABIs + deployment addresses into a shared TS module used by the keeper and web app.
// Run after `forge build` (and after a deploy): npm run abi
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const abi = (name) => JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).abi;

const depDir = join(root, "contracts", "deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}

const body = `// AUTO-GENERATED by scripts/export-abi.mjs — do not edit.
export const tusdAbi = ${JSON.stringify(abi("TUSD"))} as const;
export const vaultAbi = ${JSON.stringify(abi("FlopsVault"))} as const;
export const perpsAbi = ${JSON.stringify(abi("FlopsPerps"))} as const;
export const deployments: Record<number, { chainId: number; startBlock: number; tusd: \`0x\${string}\`; vault: \`0x\${string}\`; perps: \`0x\${string}\`; keeper: \`0x\${string}\` }> = ${JSON.stringify(deployments, null, 2)} as any;
`;

for (const target of ["keeper/src/generated", "web/src/generated"]) {
  const dir = join(root, target);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "contracts.ts"), body);
}
console.log("ABIs exported for chains:", Object.keys(deployments).join(", ") || "(none deployed yet)");
